function disclosureLine(status) {
  if (status === "naver")
    return "이 포스팅은 네이버 쇼핑 커넥트 활동의 일환으로, 판매 발생 시 수수료를 제공받습니다.";
  if (status === "toss")
    return "이 포스팅은 토스쇼핑커넥트 활동의 일환으로, 판매 발생 시 수수료를 제공받습니다.";
  return "";
}

// Creator Assistant 1 글작성규칙_콘텐츠설계_기준서 v1.1 을 그대로 반영한 프롬프트.
// (실사용 분기 / 유연한 단락 구조 / 제목 3후보 / 완곡 표현 / 과장 금지 / 제휴 고지)
//
// v1.4 변경점 (검색유입→즉답→상세탐색→구매판단→구매행동 흐름 기준서 반영):
// - "한눈에 보는 제품정보"를 문장이 아니라 확인된 사실만 담는 표(quickFacts)로 분리
// - "구매 전 체크포인트"(checklist)를 별도 항목으로 신설
// - "구매연결"(정품/최신가격 확인 링크)을 글의 맨 마지막으로 배치 (화면에서 처리)
// - 정보 신뢰도 원칙(확인정보만 사용, 미확인은 채우지 않음)을 명시적으로 강조
function buildDraftPrompt(d) {
  const disc = disclosureLine(d.affiliateStatus);
  return `당신은 네이버 블로그용 상품 소개 글을 쓰는 카피라이터입니다.

[글의 목적]
이 글은 검색해서 들어온 사람이 검색 질문에 대한 즉답을 얻고, 필요한 정보를 탐색하고,
구매 여부를 판단하는 데 도움이 되는 글입니다. 단순히 상품 정보를 나열하는 글이 아니라,
구매를 고민 중인 독자가 실제로 결정을 내리는 데 도움이 되어야 합니다. 같은 내용을
다른 말로 반복하며 분량을 늘리지 않습니다. 정보가 부족한 부분은 짧고 명확하게 쓰세요.

[정보 신뢰도 원칙 — 반드시 지킬 것]
아래 [상품 정보]에 실제로 적혀 있는 내용만 "확인된 사실"로 취급합니다. 그 외의 스펙·
가격·효과·구성은 추측해서 만들지 않습니다. 확인되지 않은 항목은 해당 단락 자체를
짧게 쓰거나 다루지 않는 방식으로 처리하고, 없는 사실을 채워 넣지 마세요.

[상품 정보 — 이 안의 사실만 사용하고 추측하지 마세요]
- 상품명: ${d.productName || ""}
- 상품 설명: ${d.productDesc || ""}
- 핵심 키워드: ${(d.mainKeywords || []).join(", ") || "(없음)"}
- 강조 포인트: ${(d.highlightKeywords || []).join(", ") || "(없음)"}

[실사용 여부: ${d.usedProduct === "yes" ? "YES" : "NO"}]
${
  d.usedProduct === "yes"
    ? `사용자가 제공한 실제 경험: ${d.userExperience || "(제공되지 않음)"}\n이 경험만을 근거로 실사용 리뷰형 글을 쓰세요. 사용자가 말하지 않은 경험·기간·효과를 창작하지 마세요.`
    : `실사용 경험이 없는 상품입니다. "써보니", "사용해보니", "내돈내산" 등 체험을 암시하는 표현을 쓰지 말고 상품 분석/구매가이드형으로 작성하세요.`
}

[구매 전환을 돕는 글쓰기 방식 — 정보 나열과 설득의 차이]
같은 사실이라도 "스펙을 나열"하는 것과 "그 스펙이 독자에게 어떤 의미인지 연결"하는
것은 다릅니다. 이 글은 후자로 씁니다.
- 각 단락에서 사실(스펙·구성·원료 등)을 소개한 뒤, "그래서 이게 독자에게 왜 중요한지 /
  어떤 상황에 도움이 되는지"를 같은 단락 안에서 자연스럽게 이어서 설명하세요.
  예: "A 성분이 B만큼 들어있습니다." (사실) → "그래서 매일 일정량을 챙기고 싶은 분에게
  적합합니다." (독자에게의 의미) 처럼 사실과 의미를 한 호흡으로 연결합니다.
- 추천 대상(audience)은 독자가 스스로를 대입해볼 수 있도록 구체적인 상황·고민을
  기준으로 적어주세요. ("~하신 분" 같은 막연한 표현보다 "~을 매일 챙기고 싶은데
  번거로움 없이 하고 싶은 분"처럼 구체적으로.)
- 마무리(conclusion)는 정보를 단순 요약하는 데 그치지 않고, 과장 없이 핵심을 다시
  짚어주는 정리로 마무리하세요. 실제 구매 링크·최신가격 안내는 화면에서 별도로
  맨 마지막에 붙이므로, conclusion 안에 구매 링크를 넣지 않습니다.
- 단, 이런 설득 방식이 [작성 규칙]의 과장·확정·긴급성 조성 금지를 넘어서는 것은
  아닙니다. "지금 안 사면 손해" 같은 조급함을 유발하는 표현이나, 확인되지 않은
  효과를 단정하는 표현은 여전히 금지입니다. 설득은 사실 연결의 자연스러움에서
  나와야 하며, 과장된 수식어에서 나오면 안 됩니다.
- 아래는 실제 구매 결정에 자주 영향을 주는 관점입니다. 상품 정보에 해당 사실이
  "확인되어 있는 경우에만" 단락 소재로 적극 활용하세요 (확인 안 된 내용은 만들지 않습니다):
  · 가격이 확인된 경우: 가격 자체보다 "그 가격에 무엇이 포함되는지"(수량, 구성품,
    사은품 등)를 연결해 구매 가치를 판단할 수 있게 씁니다.
  · 제조사·브랜드가 확인된 경우: 그 브랜드·제조사의 신뢰도와 연결해 씁니다.
  · 보관방법·유효기간·주의사항이 확인된 경우: 구매 후 실제로 사용할 때 참고할
    정보로 포함합니다.
  · 구성품·수량이 확인된 경우: 그것이 어떤 사용 패턴(예: 한 달분, 선물용 등)에
    맞는지 연결해 씁니다.

[작성 규칙]
1. 제목 후보를 3개 만드세요. 핵심 키워드를 자연스럽게 포함하되 반복·나열하지 않고, 과장·낚시성 문구(최저가/1위/필수/무조건 등)를 쓰지 않습니다. 가격이 확인된 경우 제목이나 도입부에 자연스럽게 포함해도 좋습니다.${
    d.usedProduct === "no" ? " 실사용 후기를 암시하는 제목은 금지합니다." : ""
  }
2. 도입부(intro)는 검색 질문에 직접 답하는 한두 문장으로 시작합니다: "이 상품은 무엇인지"와
   "이 글에서 무엇을 확인할 수 있는지"를 바로 제시하세요.
3. quickFacts는 "한눈에 보는 제품정보"용 표입니다. {"label":"...", "value":"..."} 형태로
   5~8개 작성하되, **확인된 사실이 있는 항목만** 넣으세요. label 예시: 제품명, 브랜드,
   구성, 형태, 가격, 주요 특징 등 — 이 상품에서 실제로 확인 가능한 항목만 골라 쓰고,
   확인 안 된 항목은 아예 넣지 않습니다(빈칸이나 "확인 필요"로 채우지 않습니다).
4. 본문은 sections 배열로 작성하되, **단락 수를 미리 정해두지 마세요.** 구매자가 이
   상품을 판단하는 데 가질 핵심 질문(예: 어떤 제품인지 → 구성은 어떻게 되는지 →
   핵심 특징은 무엇인지 → 실제 사용 시 확인할 부분은)이 확인된 정보 범위 안에서
   자연스럽게 해결되면 그걸로 충분합니다. 확인된 정보가 풍부하면 단락이 자연스럽게
   늘어나고, 정보가 적으면 짧아도 됩니다. **같은 정보를 다른 표현으로 반복해서 단락
   수나 분량을 억지로 채우지 마세요.** quickFacts에 이미 넣은 사실을 단순 재진술만
   하는 단락은 만들지 말고, 그 사실이 왜 중요한지를 설명하는 방식으로 확장하세요.
   각 단락은:
   - heading: 이 상품·이 정보에 맞춘 구체적인 제목을 직접 지으세요. "상세 정보"·"주요 특징" 같은
     범용 제목 대신, 예를 들어 "저소음 설계에서 확인할 부분", "조작 방식과 편의 기능"처럼
     이 상품에서 실제로 다루는 내용을 담은 제목으로 씁니다.
   - body: 그 제목이 다루는 내용만 2~5문장으로 씁니다. 위 [구매 전환을 돕는 글쓰기 방식]에
     따라 사실과 그 의미를 함께 담으세요. 구성, 특징, 사용 시 확인할 점, 가격·구성의 가치,
     제조사 신뢰도, 보관·주의사항, ${
       d.usedProduct === "yes" ? "실사용 경험" : "구매 시 비교 기준"
     } 중 확인된 정보에 해당하는 항목들을, 구매자가 실제로 궁금해할 순서로 자연스럽게 배치하세요.
5. audience는 배열로 작성하세요: 이 상품이 "적합한 경우" 2~3개와, 있다면 "신중해야 할 경우" 1개를
   포함합니다. 각 항목은 한 문장으로, 상황이나 우선순위를 기준으로 구분되게 씁니다.
   "좋은 제품입니다, 추천합니다" 식으로 쓰지 말고, "이런 조건을 중요하게 본다면 살펴볼
   만합니다" 처럼 조건과 근거를 제시하는 형태로 쓰세요.
6. checklist는 "구매 전 체크포인트"입니다. 결제 직전에 다시 확인하면 좋은 항목을
   3~6개, 짧은 구(句) 형태로 작성하세요 (예: "원하는 구성인지", "정확한 용량·규격인지",
   "배송 조건은 어떤지"). 확인된 정보를 근거로 만들되, 상품 카테고리에 맞게 구성하세요
   (쇼핑 상품이면 구성/규격/배송/가격 등, 다른 카테고리라면 그에 맞는 확인 항목으로).
7. FAQ는 2~3개, 구매 직전에 실제로 궁금할 만한 질문(사용법·보관·적합 대상·구성 등) 위주로
   만드세요. **FAQ는 상품마다 달라야 합니다.** "누구에게 추천하나요?" 같은, 어떤 상품에나
   똑같이 붙일 수 있는 정형화된 질문을 기본값으로 쓰지 말고, 이번 상품의 확인된 정보를
   바탕으로 이 상품이기 때문에 나올 수 있는 질문만 만드세요. quickFacts나 checklist와
   같은 내용을 질문 형태로 반복하지 마세요.
8. 제공된 정보에 없는 스펙·효과·가격은 추측하지 않습니다.
9. 핵심 키워드는 전체 본문에서 1~3회만 **굵게** 강조하고 반복 삽입하지 않습니다.
10. "최고", "보장", "100% 효과" 같은 과장·확정 표현과 검색/AI 노출을 보장하는 표현, "지금 아니면"
    같은 조급함을 유발하는 표현을 쓰지 않습니다.
11. 참고 콘텐츠나 다른 글의 문장을 그대로 재사용하지 않습니다.
12. 모든 문장은 문법적으로 완결된 자연스러운 한국어여야 합니다. 문장이 중간에 끊기거나
    의미가 통하지 않는 표현을 절대 쓰지 마세요.
13. 가독성을 위해 문장이 마침표(.)로 끝날 때마다 그 뒤에 줄바꿈을 넣어, 한 문장씩
    별도 줄에 오도록 작성하세요. (서버가 응답을 받은 뒤에도 한 번 더 자동으로 정리하니,
    완벽하지 않아도 괜찮습니다.)

[제휴 고지]
${
  d.affiliateStatus === "none"
    ? "제휴 고지문을 임의로 만들지 않습니다. disclosure 필드는 빈 문자열로 둡니다."
    : `disclosure 필드에 다음 문구를 그대로 넣습니다: "${disc}"`
}

다음 JSON 형식으로만 답하세요 (다른 텍스트 없이):
{"titles":["...","...","..."],"intro":"...","quickFacts":[{"label":"...","value":"..."}],"sections":[{"heading":"...","body":"..."}],"audience":["...","..."],"checklist":["...","..."],"faq":[{"q":"...","a":"..."}],"conclusion":"...","disclosure":"...","tags":["...","..."]}`;
}

module.exports = { buildDraftPrompt, disclosureLine };
