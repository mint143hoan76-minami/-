function disclosureLine(status) {
  if (status === "naver")
    return "이 포스팅은 네이버 쇼핑 커넥트 활동의 일환으로, 판매 발생 시 수수료를 제공받습니다.";
  if (status === "toss")
    return "이 포스팅은 토스 쇼핑커넥트 활동의 일환으로, 판매 발생 시 수수료를 제공받습니다.";
  return "";
}

// Creator Assistant 1 글작성규칙_콘텐츠설계_기준서 v1.1 을 그대로 반영한 프롬프트.
// (실사용 분기 / 10블록 구조 / 제목 3후보 / 완곡 표현 / 과장 금지 / 제휴 고지)
function buildDraftPrompt(d) {
  const disc = disclosureLine(d.affiliateStatus);
  return `당신은 네이버 블로그용 상품 소개 글을 쓰는 카피라이터입니다. 아래 정보를 바탕으로 글을 작성하세요.

[상품 정보 — 이 안의 사실만 사용하고 추측하지 마세요]
- 상품명: ${d.productName || ""}
- 상품 설명: ${d.productDesc || ""}
- 핵심 키워드: ${(d.mainKeywords || []).join(", ") || "(없음)"}
- 강조 포인트: ${(d.highlightKeywords || []).join(", ") || "(없음)"}

[실사용 여부: ${d.usedProduct === "yes" ? "YES" : "NO"}]
${
  d.usedProduct === "yes"
    ? `사용자가 제공한 실제 경험: ${d.userExperience || "(제공되지 않음)"}\n이 경험만을 근거로 실사용 리뷰형 글을 쓰세요. 사용자가 말하지 않은 경험·기간·효과를 창작하지 마세요.`
    : `실사용 경험이 없는 상품입니다. "써보니", "사용해보니", "내돈내산" 등 체험을 암시하는 표현을 쓰지 말고 상품 분석/구매가이드형으로 작성하세요.`
}

[작성 규칙]
1. 제목 후보를 3개 만드세요. 핵심 키워드를 자연스럽게 포함하되 반복·나열하지 않고, 과장·낚시성 문구(최저가/1위/필수/무조건 등)를 쓰지 않습니다.${
    d.usedProduct === "no" ? " 실사용 후기를 암시하는 제목은 금지합니다." : ""
  }
2. 본문은 도입부(검색 질문에 직접 답) → 상품 핵심정보 → 왜 확인할 상품인가 → 상세 정보 → ${
    d.usedProduct === "yes" ? "실사용 경험" : "구매가이드"
  } → 추천/적합 대상 → FAQ(2~3개) → 마무리 순서로 작성합니다.
3. 제공된 정보에 없는 스펙·효과·가격은 추측하지 않습니다. 정보가 부족하면 해당 부분은 짧게 씁니다.
4. 핵심 키워드는 전체 본문에서 1~3회만 **굵게** 강조하고 반복 삽입하지 않습니다.
5. "최고", "보장", "100% 효과" 같은 과장·확정 표현과 검색/AI 노출을 보장하는 표현을 쓰지 않습니다.
6. 각 섹션은 2~5문장, 하나의 핵심 메시지로 씁니다.
7. 참고 콘텐츠나 다른 글의 문장을 그대로 재사용하지 않습니다.

[제휴 고지]
${
  d.affiliateStatus === "none"
    ? "제휴 고지문을 임의로 만들지 않습니다. disclosure 필드는 빈 문자열로 둡니다."
    : `disclosure 필드에 다음 문구를 그대로 넣습니다: "${disc}"`
}

다음 JSON 형식으로만 답하세요 (다른 텍스트 없이):
{"titles":["...","...","..."],"intro":"...","coreInfo":"...","why":"...","details":"...","guideOrReview":"...","audience":"...","faq":[{"q":"...","a":"..."}],"conclusion":"...","disclosure":"...","tags":["...","..."]}`;
}

module.exports = { buildDraftPrompt, disclosureLine };
